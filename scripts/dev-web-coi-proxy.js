#!/usr/bin/env node
// scripts/dev-web-coi-proxy.js
//
// Dev-tooling only — this script is never part of the shipped app, and
// Android/iOS (the real targets) don't need it at all, since they use
// native on-device SQLite, not the WebAssembly build this exists for.
//
// The problem: expo-sqlite's web backend runs SQLite compiled to
// WebAssembly inside a Web Worker, and needs `SharedArrayBuffer` to share
// memory between the page and that worker. Browsers only hand out a
// working `SharedArrayBuffer` to a page that is "cross-origin isolated" —
// which requires two response headers (`Cross-Origin-Opener-Policy` and
// `Cross-Origin-Embedder-Policy`) on the actual HTML document response,
// not just on its subresources.
//
// Why this can't be done from metro.config.js: that file only gets a hook
// into Metro's OWN middleware (`server.enhanceMiddleware`), and — verified
// directly while building this — the root "/" document for `expo start
// --web` is generated by a different part of Expo's dev server that runs
// *before* that hook and fully handles the response itself. Headers set
// inside `enhanceMiddleware` land on JS bundle requests but never reach
// the actual page, so `crossOriginIsolated` stays `false` no matter what.
//
// The fix: sit a tiny reverse proxy in front of the real Metro dev server,
// stamp the two headers onto *every* response that passes through it
// (documents included, since the proxy doesn't care what generated the
// response), and point the browser at the proxy's port instead of
// Metro's. `expo start --web` still runs completely normally underneath —
// this never touches Expo's own server.

const { spawn } = require("child_process");
const http = require("http");
const httpProxy = require("http-proxy");

const METRO_PORT = 8081;
// PORT is honored so this can be handed an arbitrary free port by whatever
// launches it, instead of fighting something else already bound to a
// hardcoded one.
const PROXY_PORT = Number(process.env.PORT) || Number(process.env.COI_PROXY_PORT) || 8090;

// Runs the exact same command `npm run web` would, just on a fixed port so
// the proxy always knows where to find it. `stdio: "inherit"` means Expo's
// own logs (bundling progress, console.log from the app, etc.) print
// straight to this script's terminal, same as running it directly.
const metro = spawn("npx", ["expo", "start", "--web", "--port", String(METRO_PORT)], {
  stdio: "inherit",
  // Windows' `npx` is actually `npx.cmd`, a shell script — spawning it
  // without a shell fails with EINVAL rather than running it. `shell: true`
  // runs the command through the OS shell (cmd.exe here, sh elsewhere),
  // which is what resolves `npx` to the right executable on either.
  shell: true,
});

const proxy = httpProxy.createProxyServer({
  target: `http://localhost:${METRO_PORT}`,
  ws: true, // Metro's dev server uses a WebSocket for Fast Refresh / HMR — proxy that too, or every edit would need a manual page reload.
});

// Every response passing back through the proxy — whatever generated it —
// gets these two headers added before it reaches the browser.
proxy.on("proxyRes", (proxyRes) => {
  proxyRes.headers["Cross-Origin-Opener-Policy"] = "same-origin";
  proxyRes.headers["Cross-Origin-Embedder-Policy"] = "require-corp";
});

proxy.on("error", (err, req, res) => {
  // Most common cause: the browser reached the proxy before Metro finished
  // booting. Respond instead of hanging so a manual refresh can just retry.
  console.error("[coi-proxy] proxy error:", err.message);
  if (res && !res.headersSent) {
    res.writeHead(502, { "Content-Type": "text/plain" });
    res.end("COI proxy: Metro isn't ready yet — refresh in a moment.");
  }
});

const server = http.createServer((req, res) => {
  proxy.web(req, res);
});

// WebSocket upgrade requests (Fast Refresh) go through a separate event —
// `proxy.web` alone only handles plain HTTP.
server.on("upgrade", (req, socket, head) => {
  proxy.ws(req, socket, head);
});

server.listen(PROXY_PORT, () => {
  console.log(
    `[coi-proxy] listening on http://localhost:${PROXY_PORT}, forwarding to Metro on ${METRO_PORT} with cross-origin-isolation headers added`,
  );
});

// If this script is stopped, stop the Metro child process too, rather than
// leaving an orphaned dev server bound to the port.
function shutdown() {
  metro.kill();
  server.close(() => process.exit(0));
}
process.on("SIGINT", shutdown);
process.on("SIGTERM", shutdown);
metro.on("exit", (code) => process.exit(code ?? 0));
